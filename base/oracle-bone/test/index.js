// Create reusable off-screen textarea for clipboard operations
const clipboardTextArea = document.createElement('textarea')
clipboardTextArea.style.position = 'fixed'
clipboardTextArea.style.left = '-999999px'
clipboardTextArea.style.top = '-999999px'
clipboardTextArea.setAttribute('aria-hidden', 'true')
document.body.appendChild(clipboardTextArea)

// Reusable function to copy text to clipboard
async function copyToClipboard(text) {
  try {
    await navigator.clipboard.writeText(text)
  } catch (error) {
    // Fallback for older browsers
    clipboardTextArea.value = text
    clipboardTextArea.select()
    try {
      document.execCommand('copy')
    } catch (err) {
      // Ignore errors
    }
  }
}

// Click handler for copying glyph to clipboard
document.addEventListener('DOMContentLoaded', function () {
  const markFlowDocks = document.querySelectorAll('.mark-flow-dock')

  markFlowDocks.forEach(dock => {
    dock.addEventListener('click', async function () {
      const glyph = this.textContent || this.innerText
      await copyToClipboard(glyph)
    })
  })
})
